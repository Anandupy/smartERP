  NULL_ACADEMIC_YEAR_SENTINEL,
  SEQUENCE_PLACEHOLDER,
  YEAR_PLACEHOLDER,
  SEQUENCE_PURPOSE_RULES,
  KNOWN_PLACEHOLDERS,
  SAFE_LITERAL_PATTERN,
  MAX_FORMAT_LENGTH,
