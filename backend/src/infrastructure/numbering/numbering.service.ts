import {
  BadRequestException,
  ConflictException,
  Injectable,
  InternalServerErrorException,
  Logger,
  NotFoundException,
} from '@nestjs/common';
import { v7 as uuidv7 } from 'uuid';
import { PrismaService } from '@/infrastructure/database/prisma.service';
import { PrismaTransactionClient } from '@/infrastructure/database/prisma-transaction.types';
import { EventBus } from '@/infrastructure/events/event-bus.interface';
import { NumberingConfigCreatedEvent } from '@/common/events';
import {
  AllocateNumberParams,
  NULL_ACADEMIC_YEAR_SENTINEL,
  SEQUENCE_PLACEHOLDER,
  YEAR_PLACEHOLDER,
  SEQUENCE_PURPOSE_RULES,
  ResetStrategy,
  SequencePurpose,
} from './numbering.types';
import {
  CreateNumberSequenceConfigDto,
  PreviewNumberSequenceDto,
  UpdateNumberSequenceConfigDto,
} from './dto/numbering.dto';

/**
 * The one engine that issues every human-facing business identifier.
 *
 * A second generator is never created. In particular `studentCode` is not
 * generated by the Student module — per-module generators are how an ERP ends
 * up with six incompatible numbering schemes.
 *
 * See docs/planning/student-admission-enrollment-architecture.md §34.
 */
@Injectable()
export class NumberingService {
  private readonly logger = new Logger(NumberingService.name);

  constructor(
    private readonly prisma: PrismaService,
    private readonly eventBus: EventBus,
  ) {}

  // -------------------------------------------------------------------------
  // Allocation
  // -------------------------------------------------------------------------

  /**
   * Allocate the next value for a purpose and render it.
   *
   * The caller's transaction is always passed, but whether it is *used* depends
   * on the sequence's allocation mode:
   *
   *   GAPLESS   — allocated on the caller's transaction, so it rolls back with
   *               it and leaves no hole. The counter row stays locked until the
   *               caller commits, which serialises that purpose for its scope.
   *               Correct for a receipt series an auditor checks for continuity.
   *
   *   MONOTONIC — allocated on a separate connection that commits immediately,
   *               so the caller never holds the counter lock. A caller that
   *               later rolls back burns the number and leaves a gap. Gaps in a
   *               student code are cosmetic; the contention avoided is not.
   *
   * There is deliberately no public "give me a number" entry point beyond this
   * one: allocation happens only inside a business operation that is about to
   * persist the result.
   */
  async allocate(
    params: AllocateNumberParams,
    tx: PrismaTransactionClient,
  ): Promise<string> {
    const config = await this.requireConfig(params);

    // Placeholders resolve BEFORE the counter is touched. Every read between
    // the increment and the caller's commit is lock-hold time on a row that
    // every concurrent allocation for this scope is queued behind.
    const branchCode = config.includeBranchCode
      ? await this.resolveBranchCode(params.branchId)
      : '';
    // The format is the authority on what gets rendered. `includeAcademicYear`
    // is a second knob governing the same outcome, and when the two disagree
    // the format silently loses: `{year}` renders as an empty string, the
    // separators collapse, and a yearly sequence emits the same value every
    // year with nothing to indicate why. Asking for the year is enough.
    const yearName =
      config.includeAcademicYear || config.format.includes(YEAR_PLACEHOLDER)
        ? await this.resolveAcademicYearName(params.academicYearId)
        : '';

    const counterYearId =
      config.resetStrategy === 'YEARLY'
        ? (params.academicYearId ?? null)
        : null;

    if (config.resetStrategy === 'YEARLY' && !counterYearId) {
      throw new BadRequestException({
        error: 'NUMBERING_ACADEMIC_YEAR_REQUIRED',
        message: `Sequence '${config.purpose}' resets yearly and requires an academic year.`,
        purpose: config.purpose,
      });
    }

    const client = config.allocationMode === 'GAPLESS' ? tx : this.prisma;
    const nextValue = await this.increment(client, config.id, counterYearId);

    return this.render(config, nextValue, branchCode, yearName);
  }

  /**
   * Find-or-create and increment in one statement.
   *
   * This replaces a find-then-create whose unique-violation handler could not
   * work: once the `create` raised inside a transaction, Postgres had aborted
   * it, and the `findFirst` in the `catch` failed with "current transaction is
   * aborted". That fired the first time any sequence was allocated inside a
   * transaction — which is exactly what `admit()` does.
   *
   * The `ON CONFLICT` target must name the same expression as the functional
   * unique index, or inference fails and every call inserts a new counter.
   */
  private async increment(
    client: PrismaTransactionClient,
    configId: string,
    academicYearId: string | null,
  ): Promise<number> {
    const rows = await client.$queryRawUnsafe<Array<{ currentValue: number }>>(
      `INSERT INTO "NumberSequenceCounter"
              ("id", "configId", "academicYearId", "currentValue", "updatedAt")
       VALUES ($1, $2, $3, 1, now())
       ON CONFLICT ("configId", COALESCE("academicYearId", '${NULL_ACADEMIC_YEAR_SENTINEL}'))
       DO UPDATE SET "currentValue" = "NumberSequenceCounter"."currentValue" + 1,
                     "updatedAt"    = now()
       RETURNING "currentValue"`,
      uuidv7(),
      configId,
      academicYearId,
    );

    if (!rows.length) {
      throw new InternalServerErrorException({
        error: 'NUMBERING_ALLOCATION_FAILED',
        message: 'Sequence allocation returned no value.',
      });
    }

    return rows[0].currentValue;
  }

  private render(
    config: {
      format: string;
      prefix: string | null;
      suffix: string | null;
      sequencePadding: number;
    },
    value: number,
    branchCode: string,
    yearName: string,
  ): string {
    const sequence = String(value).padStart(config.sequencePadding, '0');

    const rendered = config.format
      .replace(/\{prefix\}/g, config.prefix ?? '')
      .replace(/\{suffix\}/g, config.suffix ?? '')
      .replace(/\{branchCode\}/g, branchCode)
      .replace(/\{year\}/g, yearName)
      .replace(/\{sequence\}/g, sequence);

    // Collapse the separators left behind by an empty placeholder, so a format
    // of `{prefix}-{year}-{sequence}` with no prefix reads `2026-0001` rather
    // than `-2026-0001`.
    return rendered.replace(/-+/g, '-').replace(/^-|-$/g, '');
  }

  private async requireConfig(params: AllocateNumberParams) {
    const rules = SEQUENCE_PURPOSE_RULES[params.purpose];

    const config = await this.prisma.numberSequenceConfig.findFirst({
      where: {
        purpose: params.purpose,
        deletedAt: null,
        isActive: true,
        ...(rules.scope === 'ORGANIZATION'
          ? { scope: 'ORGANIZATION', organizationId: params.organizationId }
          : { scope: 'BRANCH', branchId: params.branchId ?? undefined }),
      },
    });

    if (!config) {
      // A missing config is a provisioning failure, not a user error. The
      // previous implementation invented one on the fly, which meant a tenant
      // could silently acquire a numbering scheme nobody chose.
      throw new InternalServerErrorException({
        error: 'NUMBERING_NOT_PROVISIONED',
        message: `No active '${params.purpose}' sequence is provisioned for this ${rules.scope.toLowerCase()}.`,
        purpose: params.purpose,
        scope: rules.scope,
      });
    }

    return config;
  }

  private async resolveBranchCode(branchId?: string | null): Promise<string> {
    if (!branchId) return '';
    const branch = await this.prisma.branch.findUnique({
      where: { id: branchId },
      select: { code: true },
    });
    return branch?.code ?? '';
  }

  private async resolveAcademicYearName(
    academicYearId?: string | null,
  ): Promise<string> {
    if (!academicYearId) return '';
    const year = await this.prisma.academicYear.findUnique({
      where: { id: academicYearId },
      select: { name: true },
    });
    return year?.name ?? '';
  }

  // -------------------------------------------------------------------------
  // Configuration
  // -------------------------------------------------------------------------

  async createConfig(
    dto: CreateNumberSequenceConfigDto,
    organizationId: string,
    branchId: string | null,
  ) {
    const rules = SEQUENCE_PURPOSE_RULES[dto.purpose];
    this.assertFormatRendersSequence(dto.format);
    this.assertYearlyFormatRendersYear(
      dto.format,
      rules.resetStrategy,
      dto.purpose,
    );

    const scopedBranchId = rules.scope === 'BRANCH' ? branchId : null;

    if (rules.scope === 'BRANCH' && !scopedBranchId) {
      throw new BadRequestException({
        error: 'NUMBERING_BRANCH_REQUIRED',
        message: `Sequence '${dto.purpose}' is branch-scoped and requires a branch context.`,
      });
    }

    const existing = await this.prisma.numberSequenceConfig.findFirst({
      where: {
        purpose: dto.purpose,
        deletedAt: null,
        ...(rules.scope === 'ORGANIZATION'
          ? { scope: 'ORGANIZATION', organizationId }
          : { scope: 'BRANCH', branchId: scopedBranchId }),
      },
    });

    if (existing) {
      throw new ConflictException({
        error: 'NUMBERING_CONFIG_EXISTS',
        message: `A '${dto.purpose}' sequence already exists for this ${rules.scope.toLowerCase()}.`,
        configId: existing.id,
      });
    }

    // Scope, reset strategy and allocation mode come from the purpose, not from
    // the caller. They are invariants of what the identifier means.
    const config = await this.prisma.numberSequenceConfig.create({
      data: {
        organizationId,
        branchId: scopedBranchId,
        scope: rules.scope,
        purpose: dto.purpose,
        allocationMode: rules.allocationMode,
        resetStrategy: rules.resetStrategy,
        prefix: dto.prefix,
        suffix: dto.suffix,
        includeBranchCode: dto.includeBranchCode ?? false,
        includeAcademicYear: dto.includeAcademicYear ?? false,
        sequencePadding: dto.sequencePadding ?? 4,
        format: dto.format,
      },
    });

    await this.eventBus.publish(
      new NumberingConfigCreatedEvent({
        configId: config.id,
        purpose: config.purpose,
        format: config.format,
      }),
    );

    return config;
  }

  /**
   * Edit a sequence's rendering.
   *
   * `prefix` and `sequencePadding` are frozen once a `NEVER`-reset sequence has
   * issued its first value. Changing the width mid-life produces
   * `STU0000000999` followed by `STU00000001000` — different lengths, which
   * breaks lexicographic ordering (so every export and printed register
   * reorders wrongly), fixed-width card and certificate layouts, and any
   * downstream pattern match.
   */
  async updateConfig(
    id: string,
    dto: UpdateNumberSequenceConfigDto,
    organizationId: string,
  ) {
    const config = await this.prisma.numberSequenceConfig.findFirst({
      where: { id, organizationId, deletedAt: null },
    });

    if (!config) {
      throw new NotFoundException('Number sequence config not found');
    }

    if (dto.format !== undefined) {
      this.assertFormatRendersSequence(dto.format);
      this.assertYearlyFormatRendersYear(
        dto.format,
        config.resetStrategy,
        config.purpose,
      );
    }

    if (config.resetStrategy === 'NEVER') {
      const changesRenderedWidth =
        (dto.sequencePadding !== undefined &&
          dto.sequencePadding !== config.sequencePadding) ||
        (dto.prefix !== undefined && dto.prefix !== config.prefix);

      if (changesRenderedWidth && (await this.hasAllocated(config.id))) {
        throw new BadRequestException({
          error: 'SEQUENCE_WIDTH_IMMUTABLE',
          message:
            `Sequence '${config.purpose}' has already issued identifiers. ` +
            'Its prefix and padding are frozen — changing them would produce ' +
            'codes of two different widths that no longer sort correctly.',
          purpose: config.purpose,
        });
      }
    }

    return this.prisma.numberSequenceConfig.update({
      where: { id: config.id },
      data: {
        prefix: dto.prefix,
        suffix: dto.suffix,
        includeBranchCode: dto.includeBranchCode,
        includeAcademicYear: dto.includeAcademicYear,
        sequencePadding: dto.sequencePadding,
        format: dto.format,
        isActive: dto.isActive,
      },
    });
  }

  /**
   * Every sequence readable from the caller's scope — the organization's own,
   * plus the current branch's.
   */
  async getConfigs(organizationId: string, branchId: string | null) {
    return this.prisma.numberSequenceConfig.findMany({
      where: {
        deletedAt: null,
        OR: [
          { scope: 'ORGANIZATION', organizationId },
          ...(branchId
            ? [{ scope: 'BRANCH' as const, branchId, organizationId }]
            : []),
        ],
      },
      orderBy: [{ scope: 'asc' }, { purpose: 'asc' }],
    });
  }

  /**
   * Render a sample without consuming a value.
   *
   * Exists because the alternative is testing a format by creating throwaway
   * applicants, which burns real numbers out of a live series.
   */
  async preview(
    id: string,
    dto: PreviewNumberSequenceDto,
    organizationId: string,
  ) {
    const config = await this.prisma.numberSequenceConfig.findFirst({
      where: { id, organizationId, deletedAt: null },
    });

    if (!config) {
      throw new NotFoundException('Number sequence config not found');
    }

    const branchCode = config.includeBranchCode
      ? await this.resolveBranchCode(config.branchId)
      : '';
    const yearName = config.includeAcademicYear
      ? await this.resolveAcademicYearName(dto.academicYearId)
      : '';

    const sampleValue = dto.sampleValue ?? 1;

    return {
      purpose: config.purpose,
      sampleValue,
      rendered: this.render(config, sampleValue, branchCode, yearName),
    };
  }

  private async hasAllocated(configId: string): Promise<boolean> {
    const counter = await this.prisma.numberSequenceCounter.findFirst({
      where: { configId, currentValue: { gt: 0 } },
      select: { id: true },
    });
    return counter !== null;
  }

  private assertFormatRendersSequence(format: string): void {
    if (!format.includes(SEQUENCE_PLACEHOLDER)) {
      throw new BadRequestException({
        error: 'NUMBERING_FORMAT_INVALID',
        message: `A sequence format must contain ${SEQUENCE_PLACEHOLDER}; without it every generated value is identical.`,
      });
    }
  }

  /**
   * A restarting counter must render the year it restarted in.
   *
   * The same species of validation as the one above, one step along: a format
   * of `{prefix}-{sequence}` on a `YEARLY` sequence issues `AD-00001` again
   * every April. `Applicant` survives that because its uniqueness rule carries
   * the academic year; `Admission @@unique([branchId, admissionNo])` does not,
   * so the branch's second year of admissions would fail on the first one.
   *
   * Caught at provisioning, where it is a one-line correction, rather than
   * twelve months later as a constraint violation nobody can explain.
   */
  private assertYearlyFormatRendersYear(
    format: string,
    resetStrategy: ResetStrategy,
    purpose: SequencePurpose,
  ): void {
    if (resetStrategy !== 'YEARLY') return;
    if (format.includes(YEAR_PLACEHOLDER)) return;

    throw new BadRequestException({
      error: 'NUMBERING_FORMAT_MISSING_YEAR',
      message: `Sequence '${purpose}' restarts every academic year, so its format must contain ${YEAR_PLACEHOLDER}. Without it the counter reissues the same values next year.`,
      purpose,
    });
  }

  /** The purposes and their fixed scope/reset/mode, for provisioning UIs. */
  getPurposeRules(): typeof SEQUENCE_PURPOSE_RULES {
    return SEQUENCE_PURPOSE_RULES;
  }

  /** @deprecated Kept only so a caller that has not migrated fails loudly. */
  async generateNextNumber(
    _branchId: string,
    _academicYearId: string | null,
    _purpose: SequencePurpose,
  ): Promise<never> {
    throw new InternalServerErrorException({
      error: 'NUMBERING_API_REMOVED',
      message:
        'generateNextNumber() is removed. Call allocate({ purpose, organizationId, branchId, academicYearId }, tx) ' +
        'so the allocation participates in the caller transaction according to the purpose allocation mode.',
    });
  }
}
