import { ApiProperty } from '@nestjs/swagger';
import { AdmissionMasterDto } from '../../masters/dto/master-response.dto';
import { MappedGuardianDto } from '../../guardians/dto/guardian-response.dto';

/**
 * An admission applicant.
 *
 * `admissionStatus` is a free-text column driven by the workflow module, not a
 * database enum; the values the transition service accepts are listed here.
 */
export class ApplicantDto {
  @ApiProperty({ example: '018f3a5b-7c9d-7e8f-9a0b-1c2d3e4f5ab0' })
  id!: string;

  @ApiProperty({ example: '018f3a5b-7c9d-7e8f-9a0b-1c2d3e4f5a6b' })
  organizationId!: string;

  @ApiProperty({ example: '018f3a5b-7c9d-7e8f-9a0b-1c2d3e4f5a6c' })
  branchId!: string;

  @ApiProperty({ example: '018f3a5b-7c9d-7e8f-9a0b-1c2d3e4f5a6d' })
  academicYearId!: string;

  @ApiProperty({
    description: 'Generated by the numbering module. Unique per branch-year.',
    example: 'ADM-MAIN-2026-0001',
  })
  admissionFormNo!: string;

  @ApiProperty({
    description: 'Generated by the numbering module. Unique per branch-year.',
    example: 'APP-MAIN-2026-0001',
  })
  applicationNo!: string;

  @ApiProperty({ example: 'Rohan' })
  firstName!: string;

  @ApiProperty({ type: String, nullable: true, example: 'Kumar' })
  middleName!: string | null;

  @ApiProperty({ example: 'Sharma' })
  lastName!: string;

  @ApiProperty({ example: 'Rohan Kumar Sharma' })
  displayName!: string;

  @ApiProperty({ type: String, format: 'date-time' })
  dob!: Date;

  @ApiProperty({ example: '018f3a5b-7c9d-7e8f-9a0b-1c2d3e4f5aa0' })
  genderId!: string;

  @ApiProperty({ type: String, nullable: true, example: 'Pune' })
  birthPlace!: string | null;

  @ApiProperty({ type: String, nullable: true, example: null })
  photoFileId!: string | null;

  @ApiProperty({ type: String, nullable: true })
  religionId!: string | null;

  @ApiProperty({ type: String, nullable: true })
  casteId!: string | null;

  @ApiProperty({ type: String, nullable: true })
  categoryId!: string | null;

  @ApiProperty({ type: String, nullable: true })
  motherTongueId!: string | null;

  @ApiProperty({ type: String, nullable: true })
  bloodGroupId!: string | null;

  @ApiProperty({ example: false })
  disabilityStatus!: boolean;

  @ApiProperty({ type: String, nullable: true })
  disabilityTypeId!: string | null;

  @ApiProperty({ type: String, nullable: true })
  disabilityNotes!: string | null;

  @ApiProperty({ type: String, nullable: true, example: '123456789012' })
  aadhaarNo!: string | null;

  @ApiProperty({ type: String, nullable: true })
  penNo!: string | null;

  @ApiProperty({ type: String, nullable: true })
  apaarId!: string | null;

  @ApiProperty({ example: '+919876543210' })
  primaryMobile!: string;

  @ApiProperty({ type: String, nullable: true })
  alternateMobile!: string | null;

  @ApiProperty({ type: String, nullable: true, example: 'rohan@example.com' })
  primaryEmail!: string | null;

  @ApiProperty({ example: '14 Ring Road' })
  currentAddressLine1!: string;

  @ApiProperty({ type: String, nullable: true })
  currentAddressLine2!: string | null;

  @ApiProperty({ example: 'Pune' })
  city!: string;

  @ApiProperty({ type: String, nullable: true, example: 'Pune' })
  district!: string | null;

  @ApiProperty({ example: 'Maharashtra' })
  state!: string;

  @ApiProperty({ example: 'India' })
  country!: string;

  @ApiProperty({ example: '411001' })
  pincode!: string;

  @ApiProperty({
    type: String,
    nullable: true,
    example: 'St. Xavier High School',
  })
  previousSchoolName!: string | null;

  @ApiProperty({ type: String, nullable: true, example: 'CBSE' })
  previousBoard!: string | null;

  @ApiProperty({ type: String, nullable: true, example: '10' })
  previousClass!: string | null;

  @ApiProperty({ type: Number, nullable: true, example: 87.5 })
  previousPercentage!: number | null;

  @ApiProperty({ type: String, nullable: true })
  tcNumber!: string | null;

  @ApiProperty({ type: String, nullable: true })
  admissionSourceId!: string | null;

  @ApiProperty({ type: String, nullable: true })
  quotaId!: string | null;

  @ApiProperty({
    description: 'Advanced only through the workflow transition endpoint.',
    enum: [
      'DRAFT',
      'SUBMITTED',
      'UNDER_REVIEW',
      'APPROVED',
      'REJECTED',
      'CANCELLED',
    ],
    example: 'DRAFT',
  })
  admissionStatus!: string;

  @ApiProperty({ type: String, nullable: true })
  internalRemarks!: string | null;

  @ApiProperty({ type: String, nullable: true })
  counsellorRemarks!: string | null;

  @ApiProperty({ type: String, nullable: true })
  assignedCounsellorId!: string | null;

  @ApiProperty({ example: false })
  transportRequired!: boolean;

  @ApiProperty({ example: false })
  hostelRequired!: boolean;

  @ApiProperty({ type: String, format: 'date-time', nullable: true })
  submittedAt!: Date | null;

  @ApiProperty({ type: String, format: 'date-time', nullable: true })
  approvedAt!: Date | null;

  @ApiProperty({ type: String, format: 'date-time', nullable: true })
  rejectedAt!: Date | null;

  @ApiProperty({ type: String, format: 'date-time', nullable: true })
  cancelledAt!: Date | null;

  @ApiProperty({
    description: 'Branch-defined fields captured on the admission form.',
    type: 'object',
    additionalProperties: true,
    nullable: true,
    example: null,
  })
  customFieldData!: Record<string, unknown> | null;

  @ApiProperty({
    description: 'Per-document submission state.',
    type: 'object',
    additionalProperties: true,
    nullable: true,
    example: null,
  })
  checklistStatus!: Record<string, unknown> | null;

  @ApiProperty({
    description:
      'Free-form labels attached to the applicant. Stored as an unconstrained JSON column, so the shape is whatever the branch writes.',
    oneOf: [
      { type: 'array', items: {} },
      { type: 'object', additionalProperties: true },
    ],
    nullable: true,
    example: null,
  })
  tags!: unknown[] | Record<string, unknown> | null;

  @ApiProperty({ type: String, nullable: true })
  formTemplateVersion!: string | null;

  @ApiProperty({ type: String, nullable: true })
  createdBy!: string | null;

  @ApiProperty({ type: String, nullable: true })
  updatedBy!: string | null;

  @ApiProperty({ type: String, nullable: true })
  approvedBy!: string | null;

  @ApiProperty({ type: String, nullable: true })
  rejectedBy!: string | null;

  @ApiProperty({ type: String, format: 'date-time' })
  createdAt!: Date;

  @ApiProperty({ type: String, format: 'date-time' })
  updatedAt!: Date;

  @ApiProperty({
    description: 'Set when soft-deleted. Null while the record is live.',
    type: String,
    format: 'date-time',
    nullable: true,
    example: null,
  })
  deletedAt!: Date | null;
}

/**
 * An applicant with the reference data a list row needs already resolved, so a
 * grid does not have to join ten master lists client-side.
 */
export class ApplicantListItemDto extends ApplicantDto {
  @ApiProperty({ type: AdmissionMasterDto })
  gender!: AdmissionMasterDto;

  @ApiProperty({ type: AdmissionMasterDto, nullable: true })
  admissionSource!: AdmissionMasterDto | null;

  @ApiProperty({ type: AdmissionMasterDto, nullable: true })
  quota!: AdmissionMasterDto | null;
}

/**
 * An applicant with every relation the detail view needs already resolved:
 * all ten reference lists, the guardians with their relation types, and the
 * enrollment if one exists.
 */
export class ApplicantDetailDto extends ApplicantDto {
  @ApiProperty({ type: AdmissionMasterDto })
  gender!: AdmissionMasterDto;

  @ApiProperty({ type: AdmissionMasterDto, nullable: true })
  religion!: AdmissionMasterDto | null;

  @ApiProperty({ type: AdmissionMasterDto, nullable: true })
  caste!: AdmissionMasterDto | null;

  @ApiProperty({ type: AdmissionMasterDto, nullable: true })
  category!: AdmissionMasterDto | null;

  @ApiProperty({ type: AdmissionMasterDto, nullable: true })
  motherTongue!: AdmissionMasterDto | null;

  @ApiProperty({ type: AdmissionMasterDto, nullable: true })
  bloodGroup!: AdmissionMasterDto | null;

  @ApiProperty({ type: AdmissionMasterDto, nullable: true })
  disabilityType!: AdmissionMasterDto | null;

  @ApiProperty({ type: AdmissionMasterDto, nullable: true })
  admissionSource!: AdmissionMasterDto | null;

  @ApiProperty({ type: AdmissionMasterDto, nullable: true })
  quota!: AdmissionMasterDto | null;

  @ApiProperty({
    description: 'Ordered by contact priority, lowest first.',
    type: [MappedGuardianDto],
  })
  guardians!: MappedGuardianDto[];

  // There is deliberately no `enrollment` here. It was declared singular while
  // the query returned an array, so the documented field never existed in a
  // response; and an applicant is an intake record, not a placement. Placements
  // are read from `/enrollments`, which is also what keeps the intake funnel
  // from carrying a twelve-year concern in its payload.
}

/** One of the applicants a duplicate check matched. */
export class DuplicateMatchDto {
  @ApiProperty({ example: '018f3a5b-7c9d-7e8f-9a0b-1c2d3e4f5ab0' })
  id!: string;

  @ApiProperty({ example: 'Rohan Kumar Sharma' })
  displayName!: string;

  @ApiProperty({ example: '+919876543210' })
  primaryMobile!: string;

  @ApiProperty({ type: String, nullable: true, example: '123456789012' })
  aadhaarNo!: string | null;

  @ApiProperty({ example: 'SUBMITTED' })
  admissionStatus!: string;
}

/**
 * The result of a pre-registration duplicate check.
 *
 * Advisory: a match does not block registration, it warns the operator that an
 * applicant with the same Aadhaar, mobile, or name-and-date-of-birth already
 * exists in the branch.
 */
export class DuplicateCheckResultDto {
  @ApiProperty({ example: false })
  hasDuplicates!: boolean;

  @ApiProperty({ type: [DuplicateMatchDto] })
  matches!: DuplicateMatchDto[];
}
