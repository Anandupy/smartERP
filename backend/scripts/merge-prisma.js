const fs = require('fs');
const path = require('path');

const prismaDir = path.join(__dirname, '..', 'prisma');
const modulesDir = path.join(prismaDir, 'modules');
const outputSchema = path.join(prismaDir, 'schema.prisma');

function findPrismaFiles(dir) {
  let results = [];
  const list = fs.readdirSync(dir);
  list.forEach((file) => {
    file = path.join(dir, file);
    const stat = fs.statSync(file);
    if (stat && stat.isDirectory()) {
      results = results.concat(findPrismaFiles(file));
    } else if (file.endsWith('.prisma')) {
      results.push(file);
    }
  });
  return results;
}

const allFiles = findPrismaFiles(modulesDir);
const sharedFiles = allFiles.filter(f => f.includes('shared'));
const otherFiles = allFiles.filter(f => !f.includes('shared'));

const filesToMerge = [...sharedFiles, ...otherFiles];

let mergedContent = '// This file is automatically generated by scripts/merge-prisma.js\n// DO NOT EDIT THIS FILE DIRECTLY\n\n';

filesToMerge.forEach(file => {
  const content = fs.readFileSync(file, 'utf-8');
  mergedContent += `// --- FROM: ${path.relative(prismaDir, file).replace(/\\/g, '/')} ---\n\n`;
  mergedContent += content + '\n\n';
});

fs.writeFileSync(outputSchema, mergedContent);
console.log('Successfully merged Prisma schema files into prisma/schema.prisma');
